const w = (s) => s.split('|');
const opt = (o) => Object.fromEntries(Object.entries(o).filter(([, v]) => v));

const syn = (level, word, answer, wrong, picture, context) => ({ kind: 'synonym', level, word, answer, wrong: w(wrong), ...opt({ picture, context }) });
const ant = (level, word, answer, wrong, picture, context) => ({ kind: 'antonym', level, word, answer, wrong: w(wrong), ...opt({ picture, context }) });
const fit = (level, text, answer, wrong, explain) => ({ kind: 'fit', level, text, answer, wrong: w(wrong), ...opt({ explain }) });
const gap = (level, text, answer, wrong, picture, explain) => ({ level, text, answer, wrong: w(wrong), ...opt({ picture, explain }) });
const idi = (level, phrase, answer, wrong, picture, context) => ({ level, phrase, answer, wrong: w(wrong), ...opt({ picture, context }) });
const snd = (level, text, answer, wrong, picture) => ({ level, text, answer, wrong: w(wrong), ...opt({ picture }) });

